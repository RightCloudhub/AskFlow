"""Narrow adapter protocols; business state remains in database services."""

from typing import Any, Protocol


class CachePort(Protocol):
    async def get(self, key: str) -> tuple[bool, Any]: ...
    async def put(self, key: str, value: Any, *, ttl: int) -> None: ...
    async def delete(self, key: str) -> None: ...


class LockPort(Protocol):
    def hold(self, key: str): ...


class LimitPort(Protocol):
    async def allow(self, key: str, *, limit: int, window: int) -> bool: ...


class ObjectPort(Protocol):
    async def put(self, data: bytes, *, content_type: str) -> str: ...
    async def url(self, key: str) -> str: ...


class EventPort(Protocol):
    async def publish(self, envelope: dict) -> None: ...


class SenderPort(Protocol):
    async def send(self, *, target: str, subject: str, body: str) -> str: ...


class SearchPort(Protocol):
    async def ids(self, db, query: str) -> list[str] | None: ...


class GatewayPort(Protocol):
    async def charge(self, db, request): ...
    async def refund(self, db, request): ...
    async def query(self, db, request_key: str): ...
